// Shared helpers: snarkjs <-> Solana alt_bn128 (EIP-197 big-endian) encodings.
// Mirrored in frontend/src/lib/zk.ts.
import { createHash } from "node:crypto";

export const CIRCUIT_ID = "payroll_v1";

const B58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";

export function b58decode(s) {
  let n = 0n;
  for (const c of s) {
    const i = B58.indexOf(c);
    if (i < 0) throw new Error(`invalid base58 char ${c}`);
    n = n * 58n + BigInt(i);
  }
  const bytes = [];
  while (n > 0n) {
    bytes.unshift(Number(n & 0xffn));
    n >>= 8n;
  }
  for (const c of s) {
    if (c !== "1") break;
    bytes.unshift(0);
  }
  return Uint8Array.from(bytes);
}

export function be32(v) {
  let n = BigInt(v);
  const out = new Uint8Array(32);
  for (let i = 31; i >= 0; i--) {
    out[i] = Number(n & 0xffn);
    n >>= 8n;
  }
  return out;
}

const hex = (b) => Buffer.from(b).toString("hex");

/** Request PDA (32 bytes) -> two 128-bit big-endian halves as decimal strings. */
export function requestHalves(pdaBase58) {
  const b = b58decode(pdaBase58);
  if (b.length !== 32) throw new Error("request PDA must decode to 32 bytes");
  return [BigInt("0x" + hex(b.slice(0, 16))).toString(), BigInt("0x" + hex(b.slice(16))).toString()];
}

export const g1 = (p) => Buffer.concat([be32(p[0]), be32(p[1])]);
// G2 Fp2 element (c0 + c1*u) is encoded c1 || c0 for the alt_bn128 syscalls.
export const g2 = (p) => Buffer.concat([be32(p[0][1]), be32(p[0][0]), be32(p[1][1]), be32(p[1][0])]);

/** snarkjs proof -> { a: 64 bytes (NOT negated; the program negates), b: 128, c: 64 } */
export function proofToSolana(proof) {
  return { a: g1(proof.pi_a), b: g2(proof.pi_b), c: g1(proof.pi_c) };
}

/** Canonical JSON of the payroll input / output, exactly as the rule set and the chain build it. */
export const payrollInputJson = (i) =>
  `{"deductions_cents":${i.deductions_cents},"salary_cents":${i.salary_cents},"tax_bps":${i.tax_bps}}`;
export const payrollOutputJson = (i, tax, net) =>
  `{"deductions_cents":${i.deductions_cents},"gross_cents":${i.salary_cents},"net_cents":${net},"tax_cents":${tax}}`;

export const sha256hex = (s) => createHash("sha256").update(s).digest("hex");

/** verification_key.json -> Rust source with alt_bn128-encoded constants. */
export function vkToRust(vk) {
  const arr = (buf) => {
    const parts = [...buf].map((x) => x.toString());
    const lines = [];
    for (let i = 0; i < parts.length; i += 16) lines.push("    " + parts.slice(i, i + 16).join(", ") + ",");
    return `[\n${lines.join("\n")}\n]`;
  };
  const ic = vk.IC.map((p) => `    ${arr(g1(p)).replace(/\n/g, "\n    ")}`).join(",\n");
  return `// @generated by zk/scripts/build.mjs from zk/build/verification_key.json. Do not edit.
// Groth16 verifying key for circuit "${CIRCUIT_ID}" (BN254), alt_bn128 big-endian encoding.

pub const NR_PUBLIC_INPUTS: usize = ${vk.nPublic};

pub const VK_ALPHA_G1: [u8; 64] = ${arr(g1(vk.vk_alpha_1))};

pub const VK_BETA_G2: [u8; 128] = ${arr(g2(vk.vk_beta_2))};

pub const VK_GAMMA_G2: [u8; 128] = ${arr(g2(vk.vk_gamma_2))};

pub const VK_DELTA_G2: [u8; 128] = ${arr(g2(vk.vk_delta_2))};

pub const VK_IC: [[u8; 64]; ${vk.IC.length}] = [
${ic}
];
`;
}
